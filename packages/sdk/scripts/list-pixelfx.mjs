import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const effectsRoot = resolve(packageRoot, '../../third_party/pixelfx/src/fx');
const outputPath = resolve(packageRoot, 'src/fx/effects.generated.ts');

function effectNames(directory = effectsRoot) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) return effectNames(path);
    if (!entry.name.endsWith('.js') || entry.name.startsWith('_')) return [];
    const source = readFileSync(path, 'utf8');
    if (!source.includes('export const meta')) return [];
    return [relative(effectsRoot, path).split(sep).join('/').replace(/\.js$/, '')];
  }).sort();
}

function source(names) {
  const loaders = names.map((name) => `  '${name}': () => import('pixelfx/fx/${name}.js'),`).join('\n');
  return `// Generated by packages/sdk/scripts/list-pixelfx.mjs. Do not edit.\n\n` +
    `const EFFECT_LOADERS = {\n${loaders}\n} satisfies Record<string, () => Promise<unknown>>;\n\n` +
    `export const EFFECT_NAMES = Object.freeze(Object.keys(EFFECT_LOADERS));\n\n` +
    `export async function loadGeneratedEffect(name: string): Promise<unknown> {\n` +
    `  const load = EFFECT_LOADERS[name as keyof typeof EFFECT_LOADERS];\n` +
    `  if (!load) throw new RangeError(\`Unknown pixelfx effect: \${name}\`);\n` +
    `  return load();\n` +
    `}\n`;
}

const names = effectNames();
const expected = source(names);
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outputPath, 'utf8');
  } catch {
    // The comparison below reports the missing generated file.
  }
  if (current !== expected) {
    console.error('packages/sdk/src/fx/effects.generated.ts is stale; run node packages/sdk/scripts/list-pixelfx.mjs');
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, expected);
  console.log(`wrote ${names.length} pixelfx effects`);
}
