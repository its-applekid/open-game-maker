import { readFile, writeFile } from 'node:fs/promises';
import { compile } from 'json-schema-to-typescript';

const target = new URL('../src/card.generated.ts', import.meta.url);
const schemas = [
  ['AssetCard', new URL('../schemas/asset-card.schema.json', import.meta.url)],
  ['MapLayoutSpec', new URL('../schemas/map-layout-spec.schema.json', import.meta.url)],
];
const parts = [];

for (const [name, url] of schemas) {
  const schema = JSON.parse(await readFile(url, 'utf8'));
  parts.push(
    await compile({ ...schema, title: name }, name, {
      additionalProperties: false,
      bannerComment: '',
      strictIndexSignatures: true,
    }),
  );
}

const generated = `/* generated by scripts/generate.mjs; do not edit */\n\n${parts.join('\n')}`;

if (process.argv.includes('--check')) {
  let current;
  try {
    current = await readFile(target, 'utf8');
  } catch {
    throw new Error('Generated card types are missing; run pnpm --filter @ogm/contracts generate');
  }
  if (current !== generated) {
    throw new Error('Generated card types are stale; run pnpm --filter @ogm/contracts generate');
  }
} else {
  await writeFile(target, generated);
}
