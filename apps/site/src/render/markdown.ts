import type { SetupContent, SetupStep, SetupSubstep } from '../schema.js';

const generatedNotice = '<!-- Generated from apps/site/content/setup.yaml; do not edit this file directly. -->';

function formatWrites(writes: string[]): string {
  return writes.length === 0 ? 'None.' : writes.map((path) => `\`${path}\``).join(', ');
}

function renderCommand(command: string): string {
  return `Command:\n\n\`\`\`sh\n${command}\n\`\`\``;
}

function renderSubstep(stepId: number, index: number, substep: SetupSubstep): string {
  const marker = substep.kind === 'run' ? '' : ` (${substep.kind.toUpperCase()})`;
  const handBack = substep.kind === 'hand' ? `Hand back to the human: ${substep.text}` : '';

  return [
    `### ${stepId}.${index + 1} ${substep.text}${marker}`,
    renderCommand(substep.command),
    `Writes: ${formatWrites(substep.writes)}`,
    `Check: ${substep.check}`,
    handBack,
  ]
    .filter(Boolean)
    .join('\n\n');
}

export function renderAgentPrompt(step: SetupStep): string {
  const handSteps = step.substeps.filter((substep) => substep.kind === 'hand');
  const handList =
    handSteps.length === 0
      ? 'Hand steps in this step: none.'
      : `Hand steps in this step: ${handSteps.map((substep) => `\`${substep.text.replace(/\.$/, '')}\``).join('; ')}.`;

  return step.agent_prompt
    .replaceAll('{{N}}', String(step.id))
    .replaceAll('{{title}}', step.title)
    .replaceAll('{{hand_list}}', handList);
}

function quotePrompt(prompt: string): string {
  return prompt
    .split('\n')
    .map((line) => (line.length === 0 ? '>' : `> ${line}`))
    .join('\n');
}

export function renderSetupMarkdown(content: SetupContent): string {
  const steps = content.steps.map((step) => {
    const substeps = step.substeps.map((substep, index) => renderSubstep(step.id, index, substep));
    return [
      `## ${step.id}. ${step.title}`,
      `Outcome: ${step.outcome}`,
      `Time: ${step.time}`,
      `Preconditions: ${step.preconditions}`,
      ...substeps,
      '### Ask an agent',
      quotePrompt(renderAgentPrompt(step)),
    ].join('\n\n');
  });

  return `${[
    '# Set up Open Game Maker 2000',
    generatedNotice,
    'Work through these steps in order. Replace the literal placeholders `<user>`, `<tailnet-host>`, `<app-origin>`, and `<github-owner>` with values for your host.',
    ...steps,
  ].join('\n\n')}\n`;
}
